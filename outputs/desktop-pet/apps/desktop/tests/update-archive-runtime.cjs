const assert = require("node:assert/strict");
const nodeFs = require("node:fs");
const rawFs = require("original-fs");
const { createHash } = require("node:crypto");
const { join } = require("node:path");
const { pathToFileURL } = require("node:url");
const [modulePath, zipPath, installDir, profileDir, expectedAsarHash] = process.argv.slice(2);
const noAsarBefore = process.noAsar;
(async () => {
  const originalArchive = join(installDir, "resources/app.asar");
  assert.ok(nodeFs.statSync(originalArchive).isDirectory(), "测试必须覆盖 Electron 的 ASAR 虚拟目录语义");
  assert.ok(rawFs.statSync(originalArchive).isFile());
  await assert.rejects(nodeFs.promises.access(originalArchive));
  const profilePath = join(profileDir, "settings.json");
  const profileBytes = rawFs.readFileSync(profilePath);
  const update = await import(pathToFileURL(modulePath).href);
  assert.equal(await update.updateFileDigest(originalArchive), expectedAsarHash);
  const { plan, manifestPath } = await update.preparePortableUpdate(zipPath, installDir, profileDir, process.pid, "--open-studio");
  const plannedArchive = plan.files.find(file => file.name === "resources/app.asar");
  assert.ok(plannedArchive, "完整计划必须包含原始 ASAR 归档");
  assert.equal(plannedArchive.sha256, expectedAsarHash);
  const stagedArchive = join(plan.stagedDir, "resources/app.asar");
  assert.ok(rawFs.statSync(stagedArchive).isFile());
  assert.equal(createHash("sha256").update(rawFs.readFileSync(stagedArchive)).digest("hex"), expectedAsarHash);
  assert.deepEqual(rawFs.readFileSync(profilePath), profileBytes);
  assert.deepEqual(JSON.parse(rawFs.readFileSync(manifestPath, "utf8")), plan);
  assert.equal(process.noAsar, noAsarBefore, "更新准备不能修改全局 ASAR 行为");
  console.log("真实 Electron ASAR 归档更新准备通过");
})().catch(error => { console.error(error); process.exitCode = 1; });